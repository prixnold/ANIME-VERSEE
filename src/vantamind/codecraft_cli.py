from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Dict, Optional

import typer
from jinja2 import Environment, BaseLoader
from rich.console import Console
from rich.panel import Panel

from .llm.ollama_client import OllamaClient


app = typer.Typer(add_completion=False, help="CodeCraft CLI - generate codebases from specs")
console = Console()


def _default_model() -> str:
    return os.getenv("VANTAMIND_MODEL", "mistral")


def parse_tags(spec: str) -> Dict[str, str]:
    tags = {}
    for match in re.finditer(r"#(\w+):([\w\-]+)", spec):
        tags[match.group(1).lower()] = match.group(2).lower()
    return tags


TEMPLATE_PY_FLASK = """
from flask import Flask, jsonify

app = Flask(__name__)

@app.get("/")
def root():
    return jsonify({"status": "ok", "app": "{{ app_name }}"})

if __name__ == "__main__":
    app.run(host="0.0.0.0", port=8000, debug=True)
"""


TEMPLATE_INDEX_HTML = """
<!doctype html>
<html>
  <head>
    <meta charset="utf-8"/>
    <meta name="viewport" content="width=device-width, initial-scale=1"/>
    <title>{{ app_name }}</title>
    <style>
      body{font-family:system-ui, -apple-system, Segoe UI, Roboto, Ubuntu, Cantarell, Noto Sans, sans-serif; padding:40px;}
      .container{max-width:760px;margin:0 auto}
    </style>
  </head>
  <body>
    <div class="container">
      <h1>{{ app_name }}</h1>
      <p>Welcome! This project was generated by CodeCraft.</p>
    </div>
  </body>
  </html>
"""


def write_file(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


@app.callback(invoke_without_command=True)
def generate(
    spec: str = typer.Argument(..., help="Describe the app, include #tags to steer output"),
    out_dir: Path = typer.Option(Path("./generated_app"), "-o", "--out", help="Output directory"),
    model: Optional[str] = typer.Option(None, help="Ollama model name"),
    dry_run: bool = typer.Option(False, help="Only print generation plan, do not write files"),
) -> None:
    """Generate a project from a natural language specification."""
    app_name = "CodeCraft App"
    tags = parse_tags(spec)
    model_name = model or _default_model()

    client = OllamaClient()
    if not client.is_available():
        console.print("[red]Ollama is not reachable. Please start it and try again.[/red]")
        raise typer.Exit(code=1)

    system = (
        "You are CodeCraft, an expert software generator. "
        "Given a user spec, propose a minimal, working project layout and key files. "
        "Return a concise summary and tech choices."
    )
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": spec},
    ]
    plan = client.chat(model=model_name, messages=messages)

    console.print(Panel.fit("Proposed plan", title="CodeCraft"))
    console.print(plan)

    if dry_run:
        return

    env = Environment(loader=BaseLoader())

    # Simple baseline scaffolds by tags
    if tags.get("lang", "python") == "python" and tags.get("framework") == "flask":
        pyproject = (
            "[project]\nname = \"generated_app\"\nversion = \"0.1.0\"\n"
            "dependencies = [\n  'flask>=3.0.0'\n]\n"
        )
        write_file(out_dir / "pyproject.toml", pyproject)
        write_file(out_dir / "app.py", env.from_string(TEMPLATE_PY_FLASK).render(app_name=app_name))
        write_file(out_dir / "README.md", f"# {app_name}\n\nGenerated by CodeCraft.\n")
    else:
        # Fallback: static HTML skeleton
        write_file(out_dir / "index.html", env.from_string(TEMPLATE_INDEX_HTML).render(app_name=app_name))
        write_file(out_dir / "README.md", f"# {app_name}\n\nGenerated by CodeCraft.\n")

    console.print(f"[green]Project written to {out_dir}[/green]")


def main() -> None:
    app()


if __name__ == "__main__":
    main()

