from __future__ import annotations

import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional

from jinja2 import Environment, BaseLoader

from ..core.config import VantaConfig
from ..core.llm_clients import ChatMessage, get_llm_client


TAG_PATTERN = re.compile(r"#(\w+)(?::([\w\-\.]+))?")


def parse_tags(text: str) -> Dict[str, Optional[str]]:
    tags: Dict[str, Optional[str]] = {}
    for match in TAG_PATTERN.finditer(text):
        key = match.group(1).lower()
        value = match.group(2)
        tags[key] = value
    return tags


TEMPLATE_README = """
# {{ app_name }}

Generated by CodeCraft CLI.

## Quickstart

{{ quickstart_instructions }}
"""


@dataclass
class GeneratedFile:
    path: str
    contents: str


class CodeCraftEngine:
    def __init__(self, config: Optional[VantaConfig] = None) -> None:
        self.config = config or VantaConfig()
        self.client = get_llm_client(self.config, prefer="auto")
        self.env = Environment(loader=BaseLoader())

    def generate_project(self, description: str, target_dir: Path) -> List[GeneratedFile]:
        tags = parse_tags(description)
        cleaned_description = TAG_PATTERN.sub("", description).strip()

        app_name = self._make_app_name(cleaned_description)
        language = tags.get("lang") or "python"
        framework = tags.get("framework") or ("flask" if language == "python" else "vanilla")

        system = (
            "You are CodeCraft, an expert software generator. Given a description,"
            " produce a minimal but runnable project with clear file paths and contents."
            " Respond ONLY with a JSON object with fields: files (list of {path, contents}),"
            " quickstart (string with commands), and notes (short string)."
        )
        user = (
            f"Description: {cleaned_description}\n"
            f"Language: {language}\nFramework: {framework}\n"
            "Requirements: minimal dependencies, runnable, include instructions."
        )
        messages = [
            ChatMessage(role="system", content=system),
            ChatMessage(role="user", content=user),
        ]
        raw = self.client.chat(messages, model=None, stream=False)

        # Heuristic parse: expect JSON with file list
        try:
            import json

            data = json.loads(raw)
        except Exception:
            # Fallback: build a basic scaffold
            data = {
                "files": [
                    {"path": "README.md", "contents": f"# {app_name}\n\nGenerated by CodeCraft."},
                    {"path": f"{app_name}/__init__.py", "contents": ""},
                    {"path": f"{app_name}/app.py", "contents": "print('Hello from CodeCraft app')\n"},
                ],
                "quickstart": "python -m pip install -r requirements.txt\npython -m {app_name}.app",
                "notes": "LLM parsing fallback",
            }

        files: List[GeneratedFile] = []
        for f in data.get("files", []):
            files.append(GeneratedFile(path=f.get("path"), contents=f.get("contents", "")))

        quickstart = data.get("quickstart") or self._default_quickstart(language, framework, app_name)

        # Ensure README exists
        if not any(f.path.lower() == "readme.md" for f in files):
            tmpl = self.env.from_string(TEMPLATE_README)
            files.append(GeneratedFile(path="README.md", contents=tmpl.render(app_name=app_name, quickstart_instructions=quickstart)))

        # Materialize to disk
        self._write_files(target_dir, files)
        return files

    def _default_quickstart(self, language: str, framework: str, app_name: str) -> str:
        if language == "python" and framework == "flask":
            return (
                "python -m venv .venv\n"
                "source .venv/bin/activate\n"
                "python -m pip install flask\n"
                f"FLASK_APP={app_name}.app:app flask run"
            )
        return "python app.py"

    def _write_files(self, target_dir: Path, files: List[GeneratedFile]) -> None:
        for f in files:
            path = target_dir / f.path
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(f.contents, encoding="utf-8")

    def _make_app_name(self, description: str) -> str:
        base = re.sub(r"[^a-zA-Z0-9]+", " ", description).strip().lower().split()
        if not base:
            return "codecraft_app"
        return "_".join(base[:3])

